"""Stable D-012 supervision failures."""
CODES = frozenset({
    "FREEZE_HASH_MISMATCH","STARTING_COMMIT_MISMATCH","D010_ENABLED",
    "NON_DISPOSABLE_DRY_RUN_DATABASE","DUPLICATE_CAMPAIGN",
    "DATABASE_ALREADY_OWNED","DATABASE_EXECUTION_CONFLICT",
    "OWNERSHIP_GENERATION_CONFLICT","OWNERSHIP_TRANSFER_INCOMPLETE",
    "STALE_LOCK_UNSAFE","PID_IDENTITY_MISMATCH","CHECKPOINT_INCOMPLETE",
    "CHECKPOINT_NOT_QUIESCENT","PROGRESS_STATE_CORRUPT",
    "WORKER_MANIFEST_INVALID","IPC_MESSAGE_INVALID","IPC_EXECUTION_MISMATCH",
    "IPC_GENERATION_MISMATCH","IPC_SEQUENCE_INVALID","IPC_IDENTITY_MISMATCH",
    "ORGANISM_START_FAILED","ORGANISM_EXIT_UNEXPECTED",
    "SUPERVISOR_RECOVERY_FAILED","EVIDENCE_PATH_INVALID",
    "PREREQUISITE_SEAL_INVALID","REAL_DEVICE_CONFIG_PROHIBITED",
})
class SupervisionError(RuntimeError):
    def __init__(self, code: str, reason: str = "") -> None:
        self.code = code if code in CODES else "SUPERVISOR_RECOVERY_FAILED"
        super().__init__(f"{self.code}:{reason}" if reason else self.code)
